const STORAGE_KEY = 'openwallpaper-locale'
const FALLBACK = 'zh-CN'

export const useI18nStore = defineStore('i18n', () => {
  const saved = typeof localStorage !== 'undefined' ? localStorage.getItem(STORAGE_KEY) : ''
  const locale = ref(locales[saved] ? saved : FALLBACK)
  const registry = ref({ ...locales })

  const localeOptions = computed(() =>
    Object.entries(registry.value).map(([code, pack]) => ({ code, label: pack.label })),
  )

  const messages = computed(() => registry.value[locale.value]?.messages ?? {})
  const fallbackMessages = computed(() => registry.value[FALLBACK]?.messages ?? {})

  function t(key, params) {
    let text = messages.value[key]
    if (text === undefined) {
      text = fallbackMessages.value[key]
    }
    if (text === undefined) {
      return key
    }
    if (params) {
      for (const [name, value] of Object.entries(params)) {
        text = text.split(`{${name}}`).join(String(value))
      }
    }
    return text
  }

  // 预设标签的显示名：存储值始终是中文，仅界面按语言映射。
  function tagLabel(name) {
    if (locale.value === FALLBACK) {
      return name
    }
    return messages.value.tagNames?.[name] ?? name
  }

  function setLocale(code) {
    if (!registry.value[code]) {
      return
    }
    locale.value = code
    try {
      localStorage.setItem(STORAGE_KEY, code)
    } catch (err) {
      /* 隐私模式下仅影响持久化 */
    }
  }

  // 运行时追加或覆盖语言包，便于用户自行扩展。
  function addLocale(code, pack) {
    if (!code || !pack?.messages) {
      return
    }
    registry.value = {
      ...registry.value,
      [code]: { label: pack.label ?? code, messages: pack.messages },
    }
  }

  return { locale, localeOptions, t, tagLabel, setLocale, addLocale }
})
